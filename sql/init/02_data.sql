-- ---------- Телеметрия ----------
-- Сюжет дня: на GPA-2 с 11:00 растёт температура подшипника №3 (и вибрация),
-- в 14:20 — внеплановая остановка. Остальные агрегаты работают штатно.
with
  g as (
    select ts
    from generate_series('2026-09-02 00:00+03'::timestamptz,
                         '2026-09-03 00:00+03'::timestamptz,
                         interval '1 minute') as ts
  ),
  base as (
    select s.id as sensor_id, s.unit_id, s.kind, s.tag, g.ts,
           extract(epoch from (g.ts - '2026-09-02 00:00+03'::timestamptz)) / 60.0 as m,   -- минута суток
           random() as r
    from sensor s cross join g
    where s.tag <> 'TE-999'
  ),
  v as (
    select sensor_id, ts,
      case
        -- ===== GPA-2: развивающийся дефект =====
        when tag = 'TE-302' then
          case
            when m < 660  then 70 + 2*sin(m/240.0) + (r-0.5)*1.6                          -- до 11:00 штатно
            when m < 840  then 70 + 2*sin(m/240.0) + (m-660)/180.0*17 + (r-0.5)*1.6       -- 11:00–14:00 рост до ~87
            when m < 860  then 87.5 + (r-0.5)*1.6                                          -- 14:00–14:20 плато
            else greatest(45, 87.5 - (m-860)*0.15) + (r-0.5)*0.6                          -- после остановки остывает
          end
        when tag = 'VT-102' then
          case
            when m < 720  then 2.3 + (r-0.5)*0.3
            when m < 860  then 2.3 + (m-720)/140.0*1.9 + (r-0.5)*0.3                       -- вибрация растёт с 12:00
            else 0.05 + r*0.05
          end
        when tag = 'PT-202' then case when m < 860 then 5.4 + (r-0.5)*0.08 else 0.1 + r*0.02 end
        when tag = 'LD-002' then case when m < 860 then 78 + (r-0.5)*3     else 0 end
        -- ===== остальные ГПА: штатный режим =====
        when kind = 'temp'      and unit_id like 'GPA%' then 68 + 3*sin(m/300.0 + 1) + (r-0.5)*1.6
        when kind = 'vibration'                          then 2.1 + (r-0.5)*0.3
        when kind = 'pressure'  and unit_id like 'GPA%' then 5.3 + (r-0.5)*0.08
        when kind = 'load'      and unit_id like 'GPA%' then 74 + 4*sin(m/400.0) + (r-0.5)*3
        -- ===== насосы =====
        when kind = 'pressure'  and unit_id like 'P-%'  then 1.20 + (r-0.5)*0.04
        when kind = 'load'      and unit_id like 'P-%'  then 65 + (r-0.5)*4
        -- ===== АВО =====
        when tag = 'TE-331' then 30 + 8*sin((m-360)/460.0) + (r-0.5)*1.2                  -- суточный ход температуры воздуха
      end as value
    from base
  )
insert into telemetry (ts, sensor_id, value)
select ts, sensor_id, round(value::numeric, 3) from v;

-- Провал связи: VT-103 не передавал данные с 02:00 до 02:35
delete from telemetry
